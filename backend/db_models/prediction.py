"""
OmniDiag — Prediction Model
=============================
Stores every prediction made by the OmniDiag system.

Each prediction record captures:
    - The raw input features sent to the model
    - The model output (prediction, confidence, diagnosis label)
    - Optional SHAP explanation data (if /explain endpoint was called)
    - Link to the patient (optional, allows anonymous predictions)
    - Link to the user who initiated the prediction

Design decisions:
    - patient_id is nullable to support anonymous predictions from the
      public API before authentication is implemented.
    - input_features is stored as JSON for full reproducibility of any
      past prediction.
    - shap_chart_data is stored as nullable JSON since /explain is an
      optional separate call after /predict.
    - probability_scale says which scale `confidence` is on. Diabetes rows
      written before the prevalence correction hold a raw-prior probability
      in the same column as rows written after it hold a corrected one; the
      two differ by roughly a factor of six near the decision threshold and
      must never be averaged, plotted or drift-compared together. Old rows
      are left NULL because the scale of a past row cannot be recovered from
      the row itself.
"""

import uuid

from sqlalchemy import JSON, Column, DateTime, Float, ForeignKey, Integer, String, func
from sqlalchemy.ext.mutable import MutableDict
from sqlalchemy.orm import relationship

from backend.database import Base


class Prediction(Base):
    """
    A single prediction record generated by the OmniDiag diagnostic system.

    Each record captures the full context of a prediction: patient features,
    model output, confidence, and optional SHAP explanation data.
    """

    __tablename__ = "predictions"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    patient_id = Column(String(36), ForeignKey("patients.id", ondelete="SET NULL"), nullable=True, index=True)
    disease = Column(String(100), nullable=False, index=True)
    input_features = Column(MutableDict.as_mutable(JSON), nullable=False)
    prediction = Column(Integer, nullable=False)  # 0 or 1
    confidence = Column(Float, nullable=False)  # 0.0–1.0
    # 'raw' | 'corrected' — the scale `confidence` is stated on. See
    # backend/probability_scale.py. NULL means "written before this column
    # existed, scale unknown".
    probability_scale = Column(String(16), nullable=True)
    diagnosis = Column(String(100), nullable=True)  # "Positive" / "Negative"
    shap_chart_data = Column(JSON, nullable=True)
    created_by = Column(String(36), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # ── Relationships ──────────────────────────────────────────────────────
    patient = relationship("Patient", back_populates="predictions", foreign_keys=[patient_id])
    created_by_user = relationship("User", back_populates="predictions", foreign_keys=[created_by])
    review_entry = relationship("ReviewQueue", back_populates="prediction", uselist=False, cascade="all, delete-orphan")

    def __repr__(self) -> str:
        return (
            f"<Prediction(id={self.id}, disease='{self.disease}', "
            f"prediction={self.prediction}, confidence={self.confidence:.3f} "
            f"[{self.probability_scale if self.probability_scale is not None else 'scale unknown'}])>"
        )
